async page => {
  const base = new URL(page.url());
  const assert = (condition, message) => { if (!condition) throw Error(message); };
  const button = label => page.getByRole('button', {name: label, exact: true});
  const textarea = page.getByRole('textbox', {name: '消息', exact: true});
  async function open(scenario, conversation = 'fixture') {
    const url = new URL(base);
    url.search = new URLSearchParams({scenario, ...(conversation ? {conversation} : {})}).toString();
    await page.goto(url.href);
    await page.bringToFront();
    if (conversation) await textarea.waitFor();
  }
  for (const colorScheme of ['light', 'dark']) for (const [width, height] of [[1440, 900], [1024, 768], [390, 844]]) {
    await page.emulateMedia({colorScheme, reducedMotion:'reduce'});
    await page.setViewportSize({width, height});
    await open('long');
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${width} ${colorScheme} overflows`);
    assert(await textarea.isVisible(), 'composer must be visible');
    const send = await button('发送消息').boundingBox();
    assert(send && send.x >= 0 && send.x + send.width <= width, 'send control must fit inside the viewport');
    assert(await textarea.evaluate(el => {
      const group = el.closest('[data-slot=input-group]');
      const toolbar = group.querySelector('[data-align=block-end]');
      const style = getComputedStyle(toolbar);
      return Number.parseFloat(style.borderTopWidth) >= 1 &&
        style.backgroundColor !== getComputedStyle(group).backgroundColor &&
        toolbar.getBoundingClientRect().top >= el.getBoundingClientRect().bottom - 1;
    }), 'composer toolbar must have its own surface and divider below the text area');
    assert(await page.locator('.chat-header').evaluate(el => el.getBoundingClientRect().top >= 0), 'the toolbar must stay on screen');
    const scroller = page.getByRole('region', {name:'消息记录'});
    assert(await scroller.evaluate(el => el.scrollHeight > el.clientHeight), 'long transcript must scroll inside the workbench');
    if (width < 720) {
      await button('打开会话列表').click();
      await page.getByRole('navigation', {name:'会话列表'}).waitFor();
      await page.keyboard.press('Escape');
      await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === '打开会话列表');
    }
    const tabs = page.getByRole('tablist', {name:'筛选对话'});
    if (width < 720) await button('打开会话列表').click();
    const unarchivedTab = tabs.getByRole('tab', {name:'未归档'});
    await unarchivedTab.press('ArrowRight');
    await tabs.getByRole('tab', {name:'已归档', selected:true}).waitFor();
    await page.getByRole('tabpanel', {name:'已归档'}).getByText('没有归档对话').waitFor();
    await unarchivedTab.click();
    await page.getByRole('tabpanel', {name:'未归档'}).getByRole('button', {name:'另一段会话', exact:true}).waitFor();
    if (width < 720) {
      await page.keyboard.press('Escape');
      await tabs.waitFor({state:'hidden'});
    }
    await button('搜索消息').click();
    await page.getByPlaceholder('搜索本对话的消息').fill('unique missing text');
    await page.getByText('没有匹配的消息').waitFor();
    await button('关闭搜索').click();
    await button('选择模型').click();
    const picker = page.getByRole('dialog', {name: '模型选择'});
    const search = picker.getByRole('combobox', {name:'搜索模型'});
    const modelGroup = picker.getByRole('group', {name:'Pi（隔离提供方）'});
    await modelGroup.waitFor();
    await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === '搜索模型');
    const offline = modelGroup.getByRole('option', {name:/offline/});
    await offline.hover();
    await page.waitForFunction(() => {
      const group = document.querySelector('[cmdk-group-items]');
      const active = group?.querySelector('[role=option][data-selected=true]');
      const inactive = group?.querySelector('[role=option][data-selected=false]');
      if (!active || !inactive) return false;
      const current = getComputedStyle(active), other = getComputedStyle(inactive);
      return active.offsetHeight >= 44 && current.backgroundColor !== other.backgroundColor && current.borderTopColor !== other.borderTopColor;
    });
    await search.fill('offline');
    await search.press('Enter');
    await picker.waitFor({state:'hidden'});
    assert((await button('选择模型').textContent()).includes('fixture/model'), 'the selected model must persist in the composer');
    await button('选择模型').click();
    await search.waitFor();
    await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === '搜索模型');
    await page.addStyleTag({content:'body > main#main :where(input):focus-visible { outline: 2px solid salmon; outline-offset: 3px; }'});
    assert(await search.evaluate(el => {
      const inputGroup = el.closest('[data-slot=input-group]');
      return getComputedStyle(el).outlineStyle === 'none' &&
        getComputedStyle(inputGroup).boxShadow !== 'none';
    }), 'model search focus ring must follow the rounded input group');
    await page.keyboard.press('Escape');
    await picker.waitFor({state:'hidden'});
    await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === '选择模型');
    const effort = button('思考强度');
    await effort.click();
    const highEffort = page.getByRole('menuitemradio', {name:'高', exact:true});
    await highEffort.click();
    await highEffort.waitFor({state:'hidden'});
    await page.waitForFunction(() => document.querySelector('button[aria-label="思考强度"]').textContent === '高');
    await effort.click();
    assert(await page.getByRole('menuitemradio', {name:'高', exact:true}).getAttribute('aria-checked') === 'true', 'Effort must display the saved choice');
    await page.keyboard.press('Escape');
    await button('选择模型').click();
    await picker.getByRole('option', {name:'快速模型'}).click();
    await picker.waitFor({state:'hidden'});
    await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === '选择模型');
    await effort.click();
    await page.getByRole('menuitemradio', {name:'关闭', exact:true}).waitFor();
    assert(await highEffort.count() === 0, 'effort choices must follow the selected model');
    assert(await page.getByRole('menuitemradio', {name:'继承提供方设置', checked:true}).count() === 1, 'unsupported effort must reset');
    await page.keyboard.press('Escape');
    const toolsButton = page.getByRole('button', {name:/应用工具（已选/});
    const layout = () => page.evaluate(() => ['body > header', '.chat-sidebar', '.chat-main'].map(selector => {
      const {x, width} = document.querySelector(selector).getBoundingClientRect();
      return [x, width];
    }));
    const before = await layout();
    await toolsButton.click();
    const tools = page.getByRole('dialog', {name:'应用工具'});
    await tools.waitFor();
    assert(JSON.stringify(await layout()) === JSON.stringify(before), 'tools dialog must preserve host and Chat rail geometry');
    await page.keyboard.press('Escape');
    await tools.waitFor({state:'hidden'});
    assert(await toolsButton.evaluate(el => el === document.activeElement), 'tools dialog must restore focus to its trigger');
    await toolsButton.click();
    await tools.getByRole('button', {name:'全部关闭'}).click();
    await tools.getByRole('button', {name:/author/}).click();
    const tool = tools.getByRole('checkbox', {name:'submit'});
    await tool.waitFor();
    const checkbox = await tool.boundingBox();
    assert(checkbox && Math.abs(checkbox.height - checkbox.width) < 1, 'host styles must preserve a square tool checkbox');
    await tools.getByText('submit', {exact:true}).click();
    assert(await tool.getAttribute('aria-checked') === 'true', 'tool field label should toggle the checkbox');
    await tools.getByRole('button', {name:'保存工具'}).click();
    await tools.waitFor({state:'hidden'});
    await button('应用工具（已选 1/100）').waitFor();
    await button('管理对话').click();
    await page.getByRole('dialog').getByRole('button', {name:'执行记录'}).waitFor();
    await page.keyboard.press('Escape');
  }
  await open('stream');
  await page.locator('[data-streamdown=strong]').filter({hasText:'正在生成第一段'}).waitFor();
  await button('停止运行').waitFor();
  await page.evaluate(() => window.advanceFixtureStream());
  await page.getByText('正在生成第一段和第二段', {exact:true}).waitFor();
  assert(await button('停止运行').isVisible(), 'the browser must show growing text before completion');
  await page.evaluate(() => window.advanceFixtureStream());
  await page.getByText('最终正文', {exact:true}).waitFor();
  assert(await page.getByText('正在生成第一段', {exact:true}).count() === 0, 'final text replaces the partial reply');
  const reads = page.getByRole('button', {name:/^read /});
  const firstRead = button('read first.txt');
  const secondRead = button('read second.txt');
  await secondRead.waitFor();
  assert(await reads.count() === 2, 'each invocation must have one tool card');
  assert(await firstRead.getAttribute('aria-expanded') === 'false', 'tool details must start collapsed');
  const firstResult = page.getByText('first result', {exact:true});
  const secondResult = page.getByText('second result', {exact:true});
  assert(!await firstResult.isVisible() && !await secondResult.isVisible(), 'results must start collapsed');
  await firstRead.press('Enter');
  await firstResult.waitFor();
  assert(await page.getByText(/"path":"first\.txt"/).count() === 0, 'expanded tools must omit raw argument JSON');
  assert(!await secondResult.isVisible(), 'out-of-order results must follow the invocation ID');
  await firstRead.click();
  await firstResult.waitFor({state:'hidden'});
  await secondRead.click();
  await secondResult.waitFor();
  const bash = button('bash git status --short');
  await bash.click();
  await page.getByText('command failed', {exact:true}).waitFor();
  assert(await bash.locator('[data-status=error]').count() === 1, 'failed tools must retain their error styling');
  await textarea.fill('Keep this draft');
  const selection = new URL(page.url()).searchParams.get('conversation');
  await page.evaluate(() => window.fixtureSetLocale('en'));
  const englishComposer = page.getByRole('textbox', {name:'Message', exact:true});
  await englishComposer.waitFor();
  assert(await englishComposer.inputValue() === 'Keep this draft', 'locale switch must preserve the draft');
  assert(new URL(page.url()).searchParams.get('conversation') === selection, 'locale switch must preserve the selected conversation');
  await secondRead.waitFor();
  await secondResult.waitFor();
  await page.evaluate(() => window.fixtureSetLocale('zh-CN'));
  await textarea.waitFor();
  await secondResult.waitFor();
  const englishUrl = new URL(base);
  englishUrl.search = new URLSearchParams({scenario:'locale', locale:'en'}).toString();
  await page.goto(englishUrl.toString());
  await page.getByRole('heading', {name:'What would you like to do?'}).waitFor();
  await open('first-message-model', '');
  await textarea.fill('使用所选模型的第一条消息');
  await button('选择模型').click();
  await page.getByRole('option', {name:/验收模型 \/ offline/}).click();
  await page.getByRole('dialog', {name:'模型选择'}).waitFor({state:'hidden'});
  await page.waitForFunction(() => location.search.includes('conversation=') && document.querySelector('[aria-label="选择模型"]').textContent.includes('fixture/model'));
  assert(await textarea.inputValue() === '使用所选模型的第一条消息', 'choosing a model must preserve the first draft');
  await button('发送消息').click();
  await page.getByText('收到，正在核对材料。').waitFor();
  assert(await page.evaluate(() => window.fixtureCalls.find(c => c.name === 'execute').args.input.snapshot.settings.model === 'fixture/model'), 'the first send must use the selected model');
  await page.evaluate(() => sessionStorage.clear());
  await open('first-message-retry', '');
  await textarea.waitFor();
  assert(await textarea.evaluate(el => {
    const composer = el.closest('form').getBoundingClientRect(), main = el.closest('.chat-main').getBoundingClientRect();
    return Math.abs(composer.top + composer.height / 2 - (main.top + main.height / 2)) < 50;
  }), 'empty Chat must center its composer');
  await textarea.fill('仅补充内容');
  assert(await textarea.evaluate(el => {el.dispatchEvent(new KeyboardEvent('keydown', {key:'Enter', isComposing:true, bubbles:true, cancelable:true})); return !window.fixtureCalls.some(c => c.name === 'create');}), 'IME confirmation must not submit');
  await button('发送消息').click();
  await page.getByText('创建结果暂未收到').waitFor();
  const createRequest = await page.evaluate(() => window.fixtureCalls.find(c => c.name === 'create').args);
  assert(await textarea.inputValue() === '仅补充内容', 'the first draft must remain visible if creation is uncertain');
  await button('核对新对话').click();
  assert(await page.evaluate(original => window.fixtureCalls.filter(c => c.name === 'create').every(c => JSON.stringify(c.args) === JSON.stringify(original)), createRequest), 'creation retry must keep its original key');
  await button('核对原请求').waitFor();
  const request = await page.evaluate(() => window.fixtureCalls.find(c => c.name === 'execute').args);
  await page.reload();
  await button('核对原请求').click();
  await page.getByText('收到，正在核对材料。').waitFor();
  await page.waitForFunction(() => document.querySelector('#chat-message').value === '');
  assert(await page.evaluate(original => JSON.stringify(window.fixtureCalls.find(c => c.name === 'execute').args) === JSON.stringify(original), request), 'retry must keep key and input');
  assert(await page.getByText('仅补充内容', {exact:true}).count() === 1, 'retry must render one message');
  await textarea.fill('继续检查');
  await button('补充指令').click();
  await page.getByText('继续检查', {exact:true}).waitFor();
  await button('停止运行').click();
  await button('停止运行').waitFor({state:'hidden'});
  await button('新对话').click();
  await page.getByRole('heading', {name:'想做些什么？'}).waitFor();
  assert(await textarea.inputValue() === '', 'starting a new conversation must show the empty composer');
  await open('markdown');
  await page.getByText('printf hello', {exact:true}).waitFor();
  await button('复制代码').waitFor();
  await page.locator('input[type=file]').setInputFiles({name:'one.png', mimeType:'image/png', buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j8x0AAAAASUVORK5CYII=', 'base64')});
  await button('移除 one.png').click();
  await button('移除 one.png').waitFor({state:'hidden'});
  await open('questions');
  const question = page.locator('form').filter({hasText:'选择范围'});
  await question.getByRole('radio').nth(1).check();
  await question.getByRole('button', {name:'提交回答'}).click();
  await question.waitFor({state:'hidden'});
  assert(await page.evaluate(() => window.fixtureCalls.find(c => c.name === 'execute').args.input.answer.value === 1), 'question must use the native option index');
  await open('archive');
  async function list() {
    if (await button('打开会话列表').isVisible()) await button('打开会话列表').click();
    return page.getByRole('navigation', {name:'会话列表'});
  }
  let sidebar = await list();
  const filter = page.getByRole('tablist', {name:'筛选对话'});
  assert(await sidebar.getByRole('button', {name:'另一段会话', exact:true}).count() === 0, 'archived conversations start out of the current list');
  await filter.getByRole('tab', {name:'已归档'}).click();
  await sidebar.getByRole('button', {name:'另一段会话', exact:true}).click();
  await button('管理对话').click();
  await button('取消归档').click();
  await page.getByRole('dialog', {name:'管理对话'}).waitFor({state:'hidden'});
  sidebar = await list();
  await sidebar.getByText('没有归档对话').waitFor();
  await filter.getByRole('tab', {name:'未归档'}).click();
  await sidebar.getByRole('button', {name:'另一段会话', exact:true}).waitFor();
  await open('sidebar-actions');
  let rowActions = (await list()).getByRole('button', {name:'操作：另一段会话', exact:true});
  await rowActions.press('Enter');
  const rowMenu = page.getByRole('menu', {name:'另一段会话的操作'});
  await rowMenu.getByRole('menuitem', {name:'置顶', exact:true}).click();
  await page.waitForFunction(() => window.fixtureCalls.some(call => call.name === 'edit' && call.args.id === 'second' && JSON.parse(call.args.patch).pinned === true));
  assert(new URL(page.url()).searchParams.get('conversation') === 'fixture', 'pinning another row must keep the open conversation');
  await rowActions.click();
  await rowMenu.getByRole('menuitem', {name:'重命名', exact:true}).click();
  const rename = page.getByRole('dialog', {name:'重命名对话'});
  await rename.getByLabel('对话名称').fill('重命名后的对话');
  await rename.getByRole('button', {name:'重命名'}).click();
  await page.waitForFunction(() => window.fixtureCalls.some(call => call.name === 'edit' && call.args.id === 'second' && JSON.parse(call.args.patch).title === '重命名后的对话'));
  await rename.waitFor({state:'hidden'});
  rowActions = (await list()).getByRole('button', {name:'操作：重命名后的对话', exact:true});
  await rowActions.click();
  await page.getByRole('menuitem', {name:'删除对话', exact:true}).click();
  const rowConfirmation = page.getByRole('alertdialog', {name:'删除对话？'});
  await rowConfirmation.getByText(/将删除「重命名后的对话」/).waitFor({timeout:3000}).catch(async error => {
    throw new Error(`${error.message}\n${await page.locator('[role=alertdialog]').allTextContents()}`);
  });
  await rowConfirmation.getByRole('button', {name:'取消'}).click();
  await rowConfirmation.waitFor({state:'hidden'});
  assert(await page.evaluate(() => window.fixtureCalls.every(call => call.name !== 'delete')), 'canceling a row deletion must leave the conversation intact');

  await open('settings');
  await button('管理对话').click();
  await button('Mind 学习范围').click();
  const scope = page.getByRole('form', {name:'Mind 学习范围设置'});
  await scope.getByText('将此对话设为私密', {exact:true}).click();
  await scope.getByRole('button', {name:'保存范围'}).click();
  await page.waitForFunction(() => window.fixtureCalls.some(call => call.name === 'observation-scope' && call.args.private === true && call.args.expectedRevision === 1));

  await open('confirmation');
  await button('管理对话').click();
  const manage = page.getByRole('dialog', {name:'管理对话'});
  const remove = manage.getByRole('button', {name:'删除对话', exact:true});
  await remove.click();
  const confirmation = page.getByRole('alertdialog', {name:'删除对话？'});
  await confirmation.waitFor();
  await page.waitForFunction(() => document.activeElement?.textContent === '取消');
  await page.keyboard.press('Escape');
  await confirmation.waitFor({state:'hidden'});
  await page.waitForFunction(() => document.activeElement?.textContent === '删除对话');
  assert(await page.evaluate(() => window.fixtureCalls.every(call => call.name !== 'delete')), 'Escape must cancel without deleting');
  await remove.click();
  await confirmation.getByRole('button', {name:'删除对话', exact:true}).click();
  await page.waitForFunction(() => window.fixtureCalls.some(call => call.name === 'delete' && call.args.confirmed === true));
  return 'six viewport/theme checks, composer, dialogs, model picker, streaming, archive and workbench regressions passed';
}
